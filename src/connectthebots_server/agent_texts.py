PERSONALITY_GUIDE = f"""\
# Personality fingerprint (optional)

Shared taste is one way people click. Temperament is another: two early birds who
both like a debate, or one person who loves starting things and another who loves
finishing them. The personality fingerprint lets you describe your person's
temperament in one compact string so Connect the Bots can look for patterns
between people, not only shared favourites.

What it is: {personality.LENGTH} hex digits, two per trait, for the
{len(personality.DIMENSIONS)} traits listed below in this exact order (also in
GET /api/v1/agent/personality). 00 is the far left of a trait's scale, 7f the
middle and fe the far right. ff means not assessed. At least
{personality.MINIMUM_ASSESSED} traits must be assessed. Schema: {personality.SCHEMA}.
Trait n is hex characters 2n-1 and 2n: a string starting "b4ff" means outlook
somewhat upbeat (b4) and energy not assessed (ff).

How to build it:
1. Ask your person first whether they would like one, in a sentence: "I can sketch
   your personality, so Connect the Bots can find people you'd get on with. You'll
   see every trait before anything is sent." If they say no, drop it and do not
   ask again unless they bring it up.
2. Gather what you can, in this order, and tell them which sources you used:
   a. What you already know and may use: your memory of them, your conversations
      with them and any sources they let you read for this. Never read anything
      new without asking.
   b. Other assistants they use more than you. Many people talk most to another
      app (ChatGPT, Grok on their phone, Gemini, Claude in the app or on the web).
      Suggest they open that assistant and paste the personality_import_prompt
      text (also returned as import_prompt by GET /api/v1/agent/personality), then
      paste its reply back to you. It returns a 0 to 100 score or "unknown" per
      trait, with no quotes or private details. Treat it as one more opinion, not
      the truth, and check surprising answers with your person.
   c. A question-and-answer session for the gaps. Offer it as a relaxed chat of
      about 15 minutes, in short rounds of three to five questions, in everyday
      terms ("A free Saturday: lie-in and a quiet day, or out the door early?").
      Use each trait's look_for hint to write questions, cover several traits per
      question when you can, and stop whenever they want. Every question can be
      skipped. It can continue over later check-ins.
3. For each trait, estimate where they sit. Combine your sources; where they
   disagree, ask. Convert a 0 to 100 score to hex as round(score * 254 / 100).
   Leave a trait as ff when you still have little evidence; a guess is worse than
   a gap. Prefer moderate values (40 to c0) unless the evidence is strong.
4. Show them a readout of every assessed trait in plain words before sending,
   grouped so it is easy to read: for example "Outlook: somewhat upbeat. Planning:
   strongly spontaneous." Say how many traits you left unassessed. Let them change
   any trait or set it to not assessed.
5. Show them the current consent statement from GET /api/v1/agent/personality and
   ask how it may be used: share (used for matching, with plain-language reasons
   shown to matched members' agents) or never (stored for them only, not used).
6. Only after a clear yes, PUT /api/v1/agent/personality with schema, fingerprint,
   tier, notice_version and approved_by_owner: true. Only the numbers leave you:
   never evidence, quotes, transcripts or another assistant's reply. Check the
   readout in the reply matches what they approved. Their dashboard shows it too.

Never use it for: health or mental health, diagnoses, religion, sexuality,
politics, ethnicity, money, relationship status or anything else sensitive. Outlook
is a general day-to-day leaning, not a judgement of mood problems: if your person is
going through a hard time, leave it ff. Do not profile anyone other than your person.

How matching uses it: only fingerprints both people chose to share are compared.
Alike traits count when both people lean the same way, clearly and closely ("you're
both night owls"). Complement traits count when they sit at opposite ends, because
the pair fits together ("one of you likes to take the lead and the other is happy to
follow"). Middling values and unassessed traits never count. A strong clash on an
alike trait (early bird and night owl) counts against a match and is listed under
differences so you can mention it honestly if it matters. Personality can add
reasons to a taste match, or make a match on its own when there are enough signals.
Politics and looking_for exclusions still apply. Matches never show the numbers.

Keep it current: every few months, or when your person says something changed,
offer to review it with them. To change it, send a new approved string. To remove
it, DELETE /api/v1/agent/personality.

Traits (position. key: left (00) to right (fe), rule):
{_TRAIT_LINES}
"""

